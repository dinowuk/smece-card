function dbCountries() {
  return Object.keys(WASTE_DB).map((id) => ({ id, name: WASTE_DB[id].name }));
}
function dbCounties(countryId) {
  const c = WASTE_DB[countryId];
  if (!c) return [];
  return Object.keys(c.counties).map((id) => ({ id, name: c.counties[id].name }));
}
function dbSettlements(countryId, countyId) {
  const c = WASTE_DB[countryId] && WASTE_DB[countryId].counties[countyId];
  if (!c) return [];
  return Object.keys(c.settlements).map((id) => ({ id, name: c.settlements[id].name }));
}
function dbBins(countryId, countyId, settlementId) {
  const s =
    WASTE_DB[countryId] &&
    WASTE_DB[countryId].counties[countyId] &&
    WASTE_DB[countryId].counties[countyId].settlements[settlementId];
  return s ? s.bins : null;
}

function buildNotifyAutomation(title, bins, notifyService, notifyTime, automationId) {
  const binsData = bins.map((b) => ({
    label: b.label,
    dates: (b.dates || '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean),
  }));
  return {
    alias: (title || 'Smeće') + ' – obavijest dan prije odvoza',
    description: 'Automatski kreirano i održavano preko smece-card kartice. Ne mijenjaj ručno — promjene se prepisuju kod svake izmjene postavki kartice.',
    trigger: [{ trigger: 'time', at: notifyTime }],
    condition: [],
    action: [
      {
        variables: {
          tomorrow: "{{ (now() + timedelta(days=1)).strftime('%Y-%m-%d') }}",
          bins_data: binsData,
          due: "{% set ns = namespace(d=[]) %}{% for b in bins_data %}{% if tomorrow in b.dates %}{% set ns.d = ns.d + [b.label] %}{% endif %}{% endfor %}{{ ns.d | join(', ') }}",
        },
      },
      {
        if: [{ condition: 'template', value_template: '{{ due != \'\' }}' }],
        then: [
          {
            service: 'notify.' + notifyService,
            data: {
              title: 'Sutra je odvoz otpada',
              message: 'Sutra se odvozi: {{ due }}',
            },
          },
        ],
      },
    ],
    mode: 'single',
  };
}

